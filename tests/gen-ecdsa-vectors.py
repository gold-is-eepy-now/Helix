#!/usr/bin/env python3
"""Generate tests/ecdsa-vectors.h: a P-256 public key and signatures made by the Python
`cryptography` library, for tests/ecdsa-unit.c.

Run: python3 tests/gen-ecdsa-vectors.py > tests/ecdsa-vectors.h
The header is committed; regenerate only when the vectors need to change."""
import sys

from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat

MSG = b"hello helix"


def c_array(name, data):
    items = [f"0x{b:02x}" for b in data]
    lines = ["    " + ", ".join(items[i:i + 16]) for i in range(0, len(items), 16)]
    return f"static const uint8_t {name}[{len(data)}] = {{\n" + ",\n".join(lines) + "\n};\n"


def main():
    key = ec.generate_private_key(ec.SECP256R1())
    pub = key.public_key().public_bytes(Encoding.X962, PublicFormat.UncompressedPoint)
    assert len(pub) == 65 and pub[0] == 4
    d = hashes.Hash(hashes.SHA256())
    d.update(MSG)
    h = d.finalize()
    sig = key.sign(MSG, ec.ECDSA(hashes.SHA256()))
    other = key.sign(b"another message", ec.ECDSA(hashes.SHA256()))

    out = sys.stdout
    out.write("/* ecdsa-vectors.h — GENERATED by tests/gen-ecdsa-vectors.py. Do not edit. */\n")
    out.write("#ifndef HELIX_ECDSA_VECTORS_H\n#define HELIX_ECDSA_VECTORS_H\n\n#include <stdint.h>\n\n")
    out.write(c_array("ECDSA_PUB", pub))
    out.write(c_array("ECDSA_HASH", h))
    out.write(c_array("ECDSA_SIG", sig))
    out.write(c_array("ECDSA_OTHER_SIG", other))
    out.write(f"#define ECDSA_SIG_LEN {len(sig)}\n#define ECDSA_OTHER_SIG_LEN {len(other)}\n")
    out.write("\n#endif /* HELIX_ECDSA_VECTORS_H */\n")


if __name__ == "__main__":
    main()
