#!/usr/bin/env python3
"""Generate tests/rsa-vectors.h: an RSA-2048 public key and signatures made by the
Python `cryptography` library, for tests/rsa-unit.c.

Run: python3 tests/gen-rsa-vectors.py > tests/rsa-vectors.h
Regenerate only when the vectors need to change; the header is committed."""
import sys

from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import padding, rsa

MSG = b"hello helix"


def c_array(name, data):
    items = [f"0x{b:02x}" for b in data]
    lines = ["    " + ", ".join(items[i:i + 16]) for i in range(0, len(items), 16)]
    return f"static const uint8_t {name}[{len(data)}] = {{\n" + ",\n".join(lines) + "\n};\n"


def main():
    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    pub = key.public_key()
    n = pub.public_numbers().n.to_bytes(256, "big")
    e = pub.public_numbers().e.to_bytes(3, "big")
    digest = hashes.Hash(hashes.SHA256())
    digest.update(MSG)
    h = digest.finalize()

    pkcs1 = key.sign(MSG, padding.PKCS1v15(), hashes.SHA256())
    pss = key.sign(MSG, padding.PSS(mgf=padding.MGF1(hashes.SHA256()), salt_length=32), hashes.SHA256())

    # A PKCS#1 signature over a different message, to check that a valid-looking
    # signature for the wrong data is refused.
    other = key.sign(b"another message", padding.PKCS1v15(), hashes.SHA256())

    out = sys.stdout
    out.write("/* rsa-vectors.h — GENERATED by tests/gen-rsa-vectors.py. Do not edit. */\n")
    out.write("#ifndef HELIX_RSA_VECTORS_H\n#define HELIX_RSA_VECTORS_H\n\n#include <stdint.h>\n\n")
    out.write(c_array("RSA_N", n))
    out.write(c_array("RSA_E", e))
    out.write(c_array("RSA_HASH", h))
    out.write(c_array("RSA_PKCS1_SIG", pkcs1))
    out.write(c_array("RSA_PSS_SIG", pss))
    out.write(c_array("RSA_OTHER_SIG", other))
    out.write("\n#endif /* HELIX_RSA_VECTORS_H */\n")


if __name__ == "__main__":
    main()
