#!/usr/bin/env python3
"""Generate tests/x509-chain-vectors.h: a three-certificate chain, RSA-2048 root ->
EC P-256 intermediate -> EC P-256 leaf (SAN chain.example.test), made by the Python
`cryptography` library. Run: python3 tests/gen-x509-chain-vectors.py > tests/x509-chain-vectors.h"""
import datetime
import ipaddress
import sys

from cryptography import x509
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import ec, rsa
from cryptography.x509.oid import NameOID

NB = datetime.datetime(2026, 1, 1, tzinfo=datetime.timezone.utc)
NA = datetime.datetime(2036, 1, 1, tzinfo=datetime.timezone.utc)


def name(cn):
    return x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, cn)])


def build(subject, pub, issuer_name, issuer_key, ca, sans=None):
    b = (x509.CertificateBuilder().subject_name(name(subject)).issuer_name(issuer_name)
         .public_key(pub).serial_number(x509.random_serial_number())
         .not_valid_before(NB).not_valid_after(NA)
         .add_extension(x509.BasicConstraints(ca=ca, path_length=0 if ca else None), critical=True))
    if not ca:
        names = sans if sans is not None else [x509.DNSName("chain.example.test")]
        b = b.add_extension(x509.SubjectAlternativeName(names), critical=False)
    if isinstance(issuer_key, rsa.RSAPrivateKey):
        return b.sign(issuer_key, hashes.SHA256())
    return b.sign(issuer_key, hashes.SHA256())


def c_array(name_, data):
    items = [f"0x{b:02x}" for b in data]
    lines = ["    " + ", ".join(items[i:i + 16]) for i in range(0, len(items), 16)]
    return f"static const uint8_t {name_}[{len(data)}] = {{\n" + ",\n".join(lines) + "\n};\n"


def main():
    root_key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    root = build("Helix Test RSA Root", root_key.public_key(), name("Helix Test RSA Root"), root_key, True)
    inter_key = ec.generate_private_key(ec.SECP256R1())
    inter = build("Helix Test EC Intermediate", inter_key.public_key(), root.subject, root_key, True)
    leaf_key = ec.generate_private_key(ec.SECP256R1())
    leaf = build("chain.example.test", leaf_key.public_key(), inter.subject, inter_key, False)
    # A leaf whose only name is an IP address (iPAddress SAN), for hosts reached by address.
    ip_key = ec.generate_private_key(ec.SECP256R1())
    ip_leaf = build("10.0.2.2", ip_key.public_key(), inter.subject, inter_key, False,
                    sans=[x509.IPAddress(ipaddress.ip_address("10.0.2.2"))])

    from cryptography.hazmat.primitives.serialization import Encoding
    out = sys.stdout
    out.write("/* x509-chain-vectors.h — GENERATED by tests/gen-x509-chain-vectors.py. Do not edit. */\n")
    out.write("#ifndef HELIX_X509_CHAIN_VECTORS_H\n#define HELIX_X509_CHAIN_VECTORS_H\n\n#include <stdint.h>\n\n")
    for n_, c in (("chain_root", root), ("chain_inter", inter), ("chain_leaf", leaf), ("chain_ip_leaf", ip_leaf)):
        der = c.public_bytes(Encoding.DER)
        out.write(c_array(n_, der))
        out.write(f"#define {n_.upper()}_LEN {len(der)}\n")
    out.write("\n#endif /* HELIX_X509_CHAIN_VECTORS_H */\n")


if __name__ == "__main__":
    main()
