#!/usr/bin/env python3
"""Writes tests/x509-vectors.h: DER certificates made with the Python `cryptography`
library, with the values the parser must report. Run once; the output is committed.
The key material is generated fresh each run, so the header changes on every run."""
import datetime
from cryptography import x509
from cryptography.x509.oid import NameOID
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec, rsa
from cryptography.hazmat.primitives.serialization import Encoding

now = datetime.datetime(2026, 1, 1, tzinfo=datetime.timezone.utc)
later = now + datetime.timedelta(days=3650)

def name(cn):
    return x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, cn)])

def build(subject_key, subject_cn, issuer_key, issuer_cn, hash_alg, is_ca, san=None):
    b = (x509.CertificateBuilder()
         .subject_name(name(subject_cn))
         .issuer_name(name(issuer_cn))
         .public_key(subject_key.public_key())
         .serial_number(x509.random_serial_number())
         .not_valid_before(now)
         .not_valid_after(later)
         .add_extension(x509.BasicConstraints(ca=is_ca, path_length=None), critical=True))
    if san:
        b = b.add_extension(x509.SubjectAlternativeName([x509.DNSName(san)]), critical=False)
    return b.sign(issuer_key, hash_alg)

ec256_root_key = ec.generate_private_key(ec.SECP256R1())
ec256_root = build(ec256_root_key, "Helix Test EC Root", ec256_root_key, "Helix Test EC Root", hashes.SHA256(), True)
ec256_leaf_key = ec.generate_private_key(ec.SECP256R1())
ec256_leaf = build(ec256_leaf_key, "leaf.example.test", ec256_root_key, "Helix Test EC Root",
                   hashes.SHA256(), False, san="leaf.example.test")
ec384_leaf_key = ec.generate_private_key(ec.SECP384R1())
ec384_leaf = build(ec384_leaf_key, "p384.example.test", ec256_root_key, "Helix Test EC Root",
                   hashes.SHA384(), False, san="p384.example.test")
rsa_root_key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
rsa_root = build(rsa_root_key, "Helix Test RSA Root", rsa_root_key, "Helix Test RSA Root", hashes.SHA256(), True)
rsa_leaf_key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
rsa_leaf = build(rsa_leaf_key, "rsa.example.test", rsa_root_key, "Helix Test RSA Root",
                 hashes.SHA256(), False, san="rsa.example.test")

def c_bytes(name_, data):
    lines = [f"static const uint8_t {name_}[] = {{"]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i+16]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"

def expected(cert):
    pub = cert.public_key()
    if isinstance(pub, rsa.RSAPublicKey):
        n = pub.public_numbers().n
        kt = "X509_KEY_RSA"
    elif isinstance(pub, ec.EllipticCurvePublicKey):
        kt = {"secp256r1": "X509_KEY_EC_P256", "secp384r1": "X509_KEY_EC_P384"}[pub.curve.name]
    bc = cert.extensions.get_extension_for_class(x509.BasicConstraints).value
    try:
        san = [n.value for n in cert.extensions.get_extension_for_class(x509.SubjectAlternativeName).value]
    except x509.ExtensionNotFound:
        san = []
    sig_oid = cert.signature_algorithm_oid.dotted_string
    return {
        "not_before": int(cert.not_valid_before_utc.timestamp()),
        "not_after": int(cert.not_valid_after_utc.timestamp()),
        "key": kt,
        "is_ca": 1 if bc.ca else 0,
        "san": san,
        "sig_oid": sig_oid,
    }

out = ["/* x509-vectors.h — GENERATED by tests/gen-x509-vectors.py. Do not edit. */\n#ifndef HELIX_X509_VECTORS_H\n#define HELIX_X509_VECTORS_H\n\n#include <stdint.h>\n\n"]
certs = {"ec256_root": ec256_root, "ec256_leaf": ec256_leaf, "ec384_leaf": ec384_leaf,
         "rsa_root": rsa_root, "rsa_leaf": rsa_leaf}
for k, v in certs.items():
    out.append(c_bytes(k, v.public_bytes(Encoding.DER)))
    out.append(f"/* {k}: {expected(v)} */\n")
    out.append(f"#define {k.upper()}_LEN sizeof {k}\n\n")
out.append("#endif /* HELIX_X509_VECTORS_H */\n")
open("tests/x509-vectors.h", "w").write("".join(out))
for k, v in certs.items():
    print(k, expected(v))
