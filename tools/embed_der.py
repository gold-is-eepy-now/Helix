#!/usr/bin/env python3
"""Embed a binary file as a C array: embed_der.py IN OUT.c SYMBOL.

Writes `const uint8_t SYMBOL[]` and `const size_t SYMBOL_len`. Used only to put the
test CA into test builds (see tests/tls-test-ca.sh and kernel/Makefile)."""
import sys


def main():
    src, dst, sym = sys.argv[1], sys.argv[2], sys.argv[3]
    data = open(src, "rb").read()
    items = [f"0x{b:02x}" for b in data]
    lines = ["    " + ", ".join(items[i:i + 16]) for i in range(0, len(items), 16)]
    with open(dst, "w") as f:
        f.write("/* GENERATED by tools/embed_der.py from " + src + ". Do not edit. */\n")
        f.write("#include <stddef.h>\n#include <stdint.h>\n\n")
        f.write(f"const uint8_t {sym}[{len(data)}] = {{\n" + ",\n".join(lines) + "\n};\n")
        f.write(f"const size_t {sym}_len = {len(data)};\n")


if __name__ == "__main__":
    main()
