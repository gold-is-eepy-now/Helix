#!/usr/bin/env python3
"""Generates kernel/src/trust_roots.c from a PEM bundle of trusted root certificates.

Usage: tools/gen-trust-roots.py [bundle.pem]
Default bundle: /etc/ssl/certs/ca-certificates.crt (the Debian ca-certificates package,
which carries Mozilla's root list). Each certificate is embedded as DER bytes so the
kernel can check chains without a filesystem. Regenerate when the bundle is updated."""
import base64
import re
import sys

src = sys.argv[1] if len(sys.argv) > 1 else "/etc/ssl/certs/ca-certificates.crt"
text = open(src, "r").read()
blocks = re.findall(r"-----BEGIN CERTIFICATE-----(.*?)-----END CERTIFICATE-----", text, re.S)
ders = [base64.b64decode("".join(b.split())) for b in blocks]

out = []
out.append("/* trust_roots.c — GENERATED by tools/gen-trust-roots.py. Do not edit.\n"
           " * Source: %s (%d certificates). */\n" % (src, len(ders)))
out.append('#include "trust_roots.h"\n\n')
for i, der in enumerate(ders):
    out.append("static const uint8_t root_%d[] = {\n" % i)
    for j in range(0, len(der), 16):
        out.append("    " + ", ".join("0x%02x" % b for b in der[j:j + 16]) + ",\n")
    out.append("};\n")
out.append("\nconst trust_root_t trust_roots[] = {\n")
for i, der in enumerate(ders):
    out.append("    { root_%d, sizeof root_%d },\n" % (i, i))
out.append("};\n")
out.append("const size_t trust_root_count = %d;\n" % len(ders))
open("kernel/src/trust_roots.c", "w").write("".join(out))
print("wrote kernel/src/trust_roots.c with %d roots, %d DER bytes" % (len(ders), sum(map(len, ders))))
